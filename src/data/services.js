export const getServiceBySlug = (slug) =>
  services.find((service) => service.slug === slug);

export const getServicePath = (service) =>
  service.canonicalPath || `/services/${service.slug}`;

export const showcaseServices = services.filter((service) => service.showcase);

export const relatedServices = (service, limit = 3) => {
  const others = services.filter((item) => item.slug !== service.slug);
  const sameFamily = others.filter((item) => item.family === service.family);
  const rest = others.filter((item) => item.family !== service.family);
  return [...sameFamily, ...rest].slice(0, limit);
};
